package codegen

import (
	"errors"
	"fmt"
	"strings"
)

// Key modes: how a row gets its primary key on create.
const (
	// KeyAuto: the database assigns it (IDENTITY, bigserial, AUTO_INCREMENT).
	KeyAuto = "auto"
	// KeyGenerated: a bigint the module assigns, from Deps.NewID (a
	// snowflake generator; ids.Next by default). Tables of other services
	// usually take their ids this way.
	KeyGenerated = "generated"
	// KeyInput: the client gives it in the create form and it never changes:
	// a natural key such as cfg_key, code or level.
	KeyInput = "input"
)

var keyModes = []string{KeyAuto, KeyGenerated, KeyInput}

// primaryKey returns the single primary key column of t.
func primaryKey(t Table) (Column, error) {
	var pk []Column
	for _, c := range t.Columns {
		if c.Primary {
			pk = append(pk, c)
		}
	}
	switch {
	case len(pk) == 0:
		return Column{}, errors.New("表没有主键")
	case len(pk) > 1:
		return Column{}, errors.New("不支持复合主键；(主表 ID, 语言) 这类子表可以作为主表的子表一起生成（children）")
	}
	if _, ok := keyType(pk[0]); !ok {
		return Column{}, fmt.Errorf("主键 %s 的类型 %s 不受支持（支持 bigint、integer、smallint 和文本）", pk[0].Name, pk[0].UDT)
	}
	return pk[0], nil
}

// keyType is how a primary key column is generated: a bigint is an ID (a
// string in JSON), integers and text keep their kinds.
func keyType(c Column) (typeInfo, bool) {
	switch c.UDT {
	case "int8":
		return typeInfo{kind: kindID, goType: "int64"}, true
	case "int4":
		return typeInfo{kind: kindInt, goType: "int"}, true
	case "int2":
		return typeInfo{kind: kindInt16, goType: "int16"}, true
	case "varchar", "bpchar", "text":
		return typeInfo{kind: kindString, goType: "string"}, true
	}
	return typeInfo{}, false
}

// autoKey reports a key the database assigns.
func autoKey(c Column) bool {
	return c.Identity || strings.HasPrefix(c.Default, "nextval(")
}

// defaultKeyMode: database-assigned keys stay so, other bigint keys are
// generated by the module, the rest are typed in.
func defaultKeyMode(c Column) string {
	switch {
	case autoKey(c):
		return KeyAuto
	case c.UDT == "int8":
		return KeyGenerated
	default:
		return KeyInput
	}
}

// keyModeProblem checks a requested key mode against the key column.
func keyModeProblem(c Column, mode string) string {
	switch mode {
	case KeyAuto:
		if !autoKey(c) {
			return fmt.Sprintf("主键 %s 不是自增列，不能用 auto；用 generated（程序生成）或 input（手填）", c.Name)
		}
	case KeyGenerated:
		if c.UDT != "int8" {
			return fmt.Sprintf("generated 只用于 bigint 主键；%s 是 %s，用 input", c.Name, c.UDT)
		}
		if autoKey(c) {
			return fmt.Sprintf("主键 %s 由数据库自增，不能用 generated", c.Name)
		}
	case KeyInput:
		if autoKey(c) {
			return fmt.Sprintf("主键 %s 由数据库自增，不能手填", c.Name)
		}
	default:
		return "keyMode 须为 " + strings.Join(keyModes, "、") + " 之一"
	}
	return ""
}

// keyGo is the Go type of the key value; keyBits the bit size of integer
// keys for strconv.
func (d *tmplData) keyGo() (goType string, bits int) {
	switch d.PK.Kind {
	case kindID:
		return "int64", 64
	case kindInt:
		return "int", 32
	case kindInt16:
		return "int16", 16
	}
	return "string", 0
}

// keyZero is the Go zero value of the key, refused on create for input keys.
func (d *tmplData) keyZero() string {
	if d.PK.Kind == kindString {
		return `""`
	}
	return "0"
}
